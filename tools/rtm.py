#!/usr/bin/env python3
"""Requirements traceability matrix: requirement <-> tests <-> defects, both directions.

Inputs: requirements/requirements.yaml, C unit test results (build/unit/*.xml, test names contain
REQ_xx), system test results (reports/out/systest.json, @pytest.mark.req), defects/DEF-*.md.
Output: docs/rtm.md and reports/out/rtm.json. Exit 1 if a requirement has no test, a test names an
unknown requirement, or a defect names an unknown requirement.
"""
import glob
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def load_defects():
    out = []
    for p in sorted(glob.glob(str(ROOT / "defects" / "DEF-*.md"))):
        meta = yaml.safe_load(Path(p).read_text().split("---")[1])
        meta["file"] = str(Path(p).relative_to(ROOT))
        out.append(meta)
    return out


def unit_results():
    res = []
    files = sorted(glob.glob(str(ROOT / "build" / "unit" / "*.xml")))
    for f in files:
        for tc in ET.parse(f).getroot().iter("testcase"):
            name = f"{tc.get('classname')}.{tc.get('name')}"
            reqs = sorted({f"REQ-{m}" for m in re.findall(r"REQ_(\d\d)", tc.get("name"))})
            res.append({"id": name, "kind": "unit", "reqs": reqs,
                        "outcome": "failed" if tc.find("failure") is not None else "passed"})
    if not files:  # not run: fall back to the names in the sources so the matrix still shows links
        for src in sorted((ROOT / "ecu" / "tests").glob("test_*.c")):
            for name in re.findall(r'\{"(test_\w+)"', src.read_text()):
                reqs = sorted({f"REQ-{m}" for m in re.findall(r"REQ_(\d\d)", name)})
                res.append({"id": f"unit.{src.stem[5:]}.{name}", "kind": "unit", "reqs": reqs, "outcome": "not run"})
    return res


def system_results():
    p = ROOT / "reports" / "out" / "systest.json"
    if not p.exists():
        return []
    return [{"id": t["nodeid"], "kind": "system", "reqs": t["reqs"], "outcome": t["outcome"]}
            for t in json.loads(p.read_text())["tests"]]


def fuzz_results():
    p = ROOT / "reports" / "out" / "fuzz.json"
    if not p.exists():
        return []
    f = json.loads(p.read_text())
    return [{"id": f"fuzz.libfuzzer_ecu ({f['seconds']} s, {f['executions']} runs)", "kind": "fuzz", "reqs": ["REQ-19"],
             "outcome": "passed" if f["exit_code"] == 0 else "failed"}]


def build():
    reqs = yaml.safe_load((ROOT / "requirements" / "requirements.yaml").read_text())["requirements"]
    ids = [r["id"] for r in reqs]
    tests = unit_results() + system_results() + fuzz_results()
    defects = load_defects()
    problems = []
    rows = []
    for r in reqs:
        ts = [t for t in tests if r["id"] in t["reqs"]]
        ds = [d for d in defects if r["id"] in d.get("requirements", [])]
        verdict = "not verified" if not ts else ("FAIL" if any(t["outcome"] == "failed" for t in ts)
                                                  else ("PASS" if all(t["outcome"] == "passed" for t in ts) else "partial"))
        if not ts:
            problems.append(f"{r['id']} has no test")
        rows.append({"id": r["id"], "title": r["title"], "category": r["category"], "verdict": verdict,
                     "unit": [t["id"] for t in ts if t["kind"] == "unit"], "system": [t["id"] for t in ts if t["kind"] == "system"],
                     "defects": [d["id"] for d in ds]})
    for t in tests:
        for q in t["reqs"]:
            if q not in ids:
                problems.append(f"test {t['id']} names unknown {q}")
    for d in defects:
        for q in d.get("requirements", []):
            if q not in ids:
                problems.append(f"{d['id']} names unknown {q}")
    untraced = [t["id"] for t in tests if not t["reqs"]]
    return {"requirements": rows, "tests": tests, "defects": defects, "untraced_tests": untraced, "problems": problems}


def write(m):
    L = ["# Requirements Traceability Matrix", "",
         "Generated by `tools/rtm.py` from `requirements/requirements.yaml`, the unit and system test results and `defects/`.", "",
         f"**{sum(r['verdict'] == 'PASS' for r in m['requirements'])}/{len(m['requirements'])} requirements verified (PASS)**, "
         f"{len(m['tests'])} tests, {len(m['defects'])} defects.", "",
         "## Requirement -> tests -> defects", "",
         "| ID | Requirement | Verdict | Unit tests | System tests | Defects |", "|---|---|---|---:|---:|---|"]
    for r in m["requirements"]:
        L.append(f"| {r['id']} | {r['title']} | {r['verdict']} | {len(r['unit'])} | {len(r['system'])} | {', '.join(r['defects']) or '-'} |")
    L += ["", "## Test -> requirement", "", "| Test | Kind | Requirements | Result |", "|---|---|---|---|"]
    for t in m["tests"]:
        L.append(f"| `{t['id']}` | {t['kind']} | {', '.join(t['reqs']) or '-'} | {t['outcome']} |")
    L += ["", "## Defect -> requirement -> tests", "", "| Defect | Severity | Status | Requirements | Regression tests |", "|---|---|---|---|---|"]
    for d in m["defects"]:
        L.append(f"| [{d['id']}](../{d['file']}) {d['title']} | {d['severity']} | {d['status']} | {', '.join(d['requirements'])} | "
                 + "<br>".join(f"`{x}`" for x in d.get("regression_tests", [])) + " |")
    if m["untraced_tests"]:
        L += ["", "## Tests without a requirement", "", "Structural or tool tests: " + ", ".join(f"`{t}`" for t in m["untraced_tests"])]
    if m["problems"]:
        L += ["", "## Problems", ""] + [f"- {p}" for p in m["problems"]]
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "rtm.md").write_text("\n".join(L) + "\n")
    out = ROOT / "reports" / "out"
    out.mkdir(parents=True, exist_ok=True)
    (out / "rtm.json").write_text(json.dumps(dict({k: v for k, v in m.items() if k != "tests"}, n_tests=len(m["tests"])), indent=1, default=str))


if __name__ == "__main__":
    m = build()
    write(m)
    print(f"RTM: {sum(r['verdict'] == 'PASS' for r in m['requirements'])}/{len(m['requirements'])} PASS, "
          f"{len(m['tests'])} tests, {len(m['problems'])} problems")
    for p in m["problems"]:
        print("  ", p)
    sys.exit(1 if m["problems"] else 0)
